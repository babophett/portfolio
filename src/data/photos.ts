// ============================================================
//  PHOTOS.ts  —  Add all your photos here.
//
//  HOW TO ADD A NEW PHOTO
//  ──────────────────────
//  1. Drop the image file into:  public/photos/your-filename.jpg
//  2. Copy any entry below and paste it into the PHOTOS array.
//  3. Update every field (see field guide below).
//  4. Save — the dev server hot-reloads instantly.
//
//  FIELD GUIDE
//  ───────────
//  src          Path from the public folder. Always start with /photos/
//  title        Short evocative title shown on cards and in the lightbox
//  location     "City / Area, State"
//  coords       Decimal degrees, e.g. "36.60 N, 118.10 W"  (or "—" if private)
//  elevation    With unit, e.g. "2,550 m"
//  season       Free text: "Late spring", "Deep winter", etc.
//  orientation  "portrait" (taller than wide) or "landscape" (wider than tall)
//  tags         Any combo of: "landscape" | "ski" | "alpine" | "desert" | "storm"
//               Used to filter the gallery. Add new tags freely.
//  collection   "work"  → appears in the main gallery
//               "about" → appears on the About page
//               You can list both: ["work", "about"]
//  forSale      true  → shows up in the print shop
//  priceFrom    Lowest print price in USD (the 12×18" matte size)
// ============================================================

